#!/usr/bin/env node
/**
 * SVG -> Android vector drawable.
 *
 *     node tools/svg-to-drawable.mjs brand/avatars/avatar-*.svg \
 *       --out composeApp/src/commonMain/composeResources/drawable
 *
 * The XML it writes is committed and the app loads it directly; Compose Multiplatform reads an
 * Android vector drawable on every target, which is why `card_*.xml` are XML and not PNGs. Run
 * this again after editing a master, and commit both halves.
 *
 * WHY A CONVERTER AND NOT A LIBRARY. The mapping is almost one-to-one — a `<path>`'s `d` becomes
 * `android:pathData`, `fill` becomes `android:fillColor` — and the masters under `brand/` are
 * written by hand, for this. A general SVG is a much larger language than that (transforms,
 * gradients, clip paths, `<use>`, CSS), and a converter that silently accepted those and dropped
 * them would produce a drawable that is wrong in a way nobody sees until it renders. So this one
 * REFUSES what it does not understand rather than approximating it: an element it has no mapping
 * for is an error naming the file and the tag, which is a build you can fix instead of a picture
 * you have to notice.
 *
 * If a master ever genuinely needs groups or gradients, teach this file that case deliberately.
 * The point is that the decision stays visible.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { basename, join } from 'node:path';

/** Attributes we map, SVG name -> vector drawable name. Anything else on a path is an error. */
const PATH_ATTRS = {
  d: 'android:pathData',
  fill: 'android:fillColor',
  'fill-rule': 'android:fillType',
  stroke: 'android:strokeColor',
  'stroke-width': 'android:strokeWidth',
  'stroke-linecap': 'android:strokeLineCap',
  'stroke-linejoin': 'android:strokeLineJoin',
};

/** SVG's fill-rule values, spelled the way a vector drawable spells them. */
const FILL_TYPE = { evenodd: 'evenOdd', nonzero: 'nonZero' };

/** Read `key="value"` pairs out of one tag's attribute text. */
function attrsOf(tag) {
  const out = {};
  for (const m of tag.matchAll(/([a-zA-Z-]+)\s*=\s*"([^"]*)"/g)) out[m[1]] = m[2];
  return out;
}

function convert(svg, file) {
  // Strip comments first: a master carries its reasoning, and none of it should reach the XML,
  // where it would be duplicated prose nobody edits.
  const body = svg.replace(/<!--[\s\S]*?-->/g, '');

  const root = body.match(/<svg\b([^>]*)>/);
  if (!root) throw new Error(`${file}: no <svg> element`);
  const svgAttrs = attrsOf(root[1]);

  const viewBox = (svgAttrs.viewBox ?? '').trim().split(/[\s,]+/).map(Number);
  if (viewBox.length !== 4 || viewBox.some(Number.isNaN)) {
    throw new Error(`${file}: needs a numeric viewBox`);
  }
  const [minX, minY, vw, vh] = viewBox;
  if (minX !== 0 || minY !== 0) {
    // A non-zero origin would have to be pushed into every path's coordinates, and doing that
    // silently is how a drawable ends up offset by a few pixels nobody can account for.
    throw new Error(`${file}: viewBox must start at "0 0" (got "${svgAttrs.viewBox}")`);
  }

  // Anything that is not <svg> or <path> is refused — see the header.
  for (const m of body.matchAll(/<([a-zA-Z][a-zA-Z0-9-]*)\b/g)) {
    if (m[1] !== 'svg' && m[1] !== 'path') {
      throw new Error(`${file}: <${m[1]}> has no vector-drawable mapping; teach the converter or change the master`);
    }
  }

  const paths = [];
  for (const m of body.matchAll(/<path\b([^>]*?)\/?>/g)) {
    const a = attrsOf(m[1]);
    const lines = [];
    for (const [key, value] of Object.entries(a)) {
      const mapped = PATH_ATTRS[key];
      if (!mapped) throw new Error(`${file}: <path ${key}=…> has no mapping`);
      // `fill="none"` is SVG's way of saying "stroke only"; a vector drawable says it by simply
      // not having a fillColor, and writing "none" there paints black.
      if ((key === 'fill' || key === 'stroke') && value === 'none') continue;
      if (key === 'fill-rule') {
        const t = FILL_TYPE[value];
        if (!t) throw new Error(`${file}: unknown fill-rule "${value}"`);
        lines.push(`${mapped}="${t}"`);
        continue;
      }
      lines.push(`${mapped}="${value}"`);
    }
    if (!a.d) throw new Error(`${file}: a <path> has no "d"`);
    paths.push(`    <path\n        ${lines.join('\n        ')}/>`);
  }
  if (paths.length === 0) throw new Error(`${file}: no <path> elements`);

  // The intrinsic size is the viewBox in dp, matching `card_*.xml`. Nothing depends on it — every
  // site that draws these gives them a size — but agreeing with the deck costs nothing.
  return [
    '<!-- GENERATED by tools/svg-to-drawable.mjs from ' + file + ' — edit the master, not this. -->',
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    `    android:width="${vw}dp" android:height="${vh}dp"`,
    `    android:viewportWidth="${vw}" android:viewportHeight="${vh}">`,
    ...paths,
    '</vector>',
    '',
  ].join('\n');
}

const args = process.argv.slice(2);
const outAt = args.indexOf('--out');
if (outAt === -1) {
  console.error('usage: node tools/svg-to-drawable.mjs <master.svg…> --out <dir>');
  process.exit(2);
}
const outDir = args[outAt + 1];
const inputs = args.slice(0, outAt);
if (inputs.length === 0 || !outDir) {
  console.error('usage: node tools/svg-to-drawable.mjs <master.svg…> --out <dir>');
  process.exit(2);
}

mkdirSync(outDir, { recursive: true });
for (const file of inputs) {
  // An Android resource name takes underscores, never dashes, and a file that breaks that rule
  // fails deep inside the resource compiler rather than here.
  const name = basename(file).replace(/\.svg$/, '').replace(/-/g, '_');
  const target = join(outDir, `${name}.xml`);
  writeFileSync(target, convert(readFileSync(file, 'utf8'), file));
  console.log(`wrote ${target}`);
}
